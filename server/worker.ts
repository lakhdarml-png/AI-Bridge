export interface Env {
  DB: D1Database;
  BRIDGE_API_TOKEN: string;
  GEMINI_API_KEY?: string;
  GEMINI_MODEL?: string;
}

type TaskStatus = "queued" | "running" | "waiting_input" | "completed" | "failed";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "GET,POST,PATCH,OPTIONS",
  "Access-Control-Allow-Headers": "Authorization,Content-Type",
  "Content-Type": "application/json; charset=utf-8",
};

function json(data: unknown, status = 200): Response {
  return new Response(JSON.stringify(data), { status, headers: corsHeaders });
}

function authorized(request: Request, env: Env): boolean {
  const header = request.headers.get("Authorization") || "";
  const token = header.startsWith("Bearer ") ? header.slice(7).trim() : "";
  return Boolean(env.BRIDGE_API_TOKEN && token && token === env.BRIDGE_API_TOKEN);
}

function taskIdFromPath(pathname: string): string | null {
  const match = pathname.match(/^\/api\/tasks\/([a-f0-9-]{36})$/i);
  return match?.[1] ?? null;
}

async function createCollaborativePlan(goal: string, env: Env): Promise<string> {
  if (!env.GEMINI_API_KEY) {
    throw new Error("GEMINI_NOT_CONFIGURED");
  }

  // One economical model call for v1. The alternative view is generated by Gemini,
  // not represented as a separate Grok or ChatGPT response.
  const model = env.GEMINI_MODEL?.trim() || "gemini-2.5-flash";
  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(env.GEMINI_API_KEY)}`;
  const prompt = [
    "أنت المنسق الرئيسي في AI Bridge. أجب بالعربية الواضحة.",
    "حلل الهدف، ثم قدم وجهتي نظر مستقلتين قدر الإمكان داخل تحليلك، وبعدها قارن بينهما واختر خطة تنفيذ واحدة.",
    "مهم: لا تدّع أن ChatGPT أو Grok شاركا فعلياً؛ هذه مراجعة داخل استجابة Gemini واحدة.",
    "راعِ تقليل التكلفة: اقترح أقل عدد من استدعاءات النماذج والأدوات، ولا تستخدم خدمات مدفوعة دون ضرورة.",
    "لا تنفذ أي إجراء خارجي بنفسك. اعرض خطة قابلة للمراجعة واطلب موافقة المستخدم قبل التغييرات الحساسة.",
    "استخدم هذه العناوين بالترتيب: الهدف، التحليل الأول، وجهة النظر البديلة، المقارنة والاختلافات، خطة التنفيذ، المخاطر والتحقق، تقدير التكلفة.",
    "كن محدداً، لا تخترع معلومات، واذكر ما يحتاج إلى تحقق.",
    "",
    "هدف المستخدم:",
    goal.slice(0, 8000),
  ].join("\n");

  const response = await fetch(endpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      contents: [{ role: "user", parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.25,
        maxOutputTokens: 1800,
      },
    }),
  });

  const payload = await response.json() as {
    candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
    error?: { message?: string; status?: string };
  };

  if (!response.ok) {
    throw new Error(`GEMINI_HTTP_${response.status}: ${payload.error?.message || "Gemini request failed"}`);
  }

  const result = payload.candidates?.[0]?.content?.parts
    ?.map((part) => part.text || "")
    .join("\n")
    .trim();

  if (!result) throw new Error("Gemini returned an empty response");
  return [
    "ملاحظة الشفافية: هذه الخطة من استدعاء واحد لـ Gemini؛ لم تُستدعَ واجهات ChatGPT أو Grok.",
    "",
    result,
  ].join("\n");
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    const path = url.pathname;

    if (request.method === "OPTIONS") {
      return new Response(null, { status: 204, headers: corsHeaders });
    }

    if (path === "/health" && request.method === "GET") {
      return json({ ok: true, service: "AI Bridge Server", version: "0.5.0", mode: "collaborative-planning" });
    }

    if (!path.startsWith("/api/")) return json({ error: "Not found" }, 404);
    if (!authorized(request, env)) return json({ error: "Unauthorized" }, 401);

    if (path === "/api/status" && request.method === "GET") {
      const geminiConfigured = Boolean(env.GEMINI_API_KEY);
      return json({
        ok: true,
        server: "connected",
        storage: "connected",
        orchestration: "collaborative-planning",
        costPolicy: "one Gemini call per task; no other provider calls unless implemented and configured",
        providers: {
          chatgpt: { connected: false, mode: "not_configured" },
          grok: { connected: false, mode: "not_configured" },
          gemini: { connected: false, configured: geminiConfigured, mode: geminiConfigured ? "configured_not_tested" : "not_configured" },
        },
        note: "A configured key is not proof of a successful provider connection. Submit a task to test Gemini."
      });
    }

    if (path === "/api/tasks" && request.method === "POST") {
      let body: { goal?: unknown; project?: unknown };
      try { body = await request.json() as { goal?: unknown; project?: unknown }; }
      catch { return json({ error: "Invalid JSON body" }, 400); }

      const goal = typeof body.goal === "string" ? body.goal.trim() : "";
      const project = typeof body.project === "string" ? body.project.trim().slice(0, 120) : "default";
      if (!goal) return json({ error: "goal is required" }, 400);
      if (goal.length > 12000) return json({ error: "goal must be 12000 characters or fewer" }, 413);

      const id = crypto.randomUUID();
      const now = new Date().toISOString();
      await env.DB.prepare(
        "INSERT INTO tasks (id, project, goal, status, result, created_at, updated_at) VALUES (?, ?, ?, 'running', NULL, ?, ?)"
      ).bind(id, project || "default", goal, now, now).run();

      let status: TaskStatus = "completed";
      let result: string;
      try {
        result = await createCollaborativePlan(goal, env);
      } catch (error) {
        const message = error instanceof Error ? error.message : "Unknown error";
        if (message === "GEMINI_NOT_CONFIGURED") {
          status = "waiting_input";
          result = "يلزم إعداد GEMINI_API_KEY في Cloudflare Worker Secrets قبل أن يتمكن الجسر من تحليل المهمة. لم يتم استدعاء أي نموذج ولم تُحتسب تكلفة نموذج.";
        } else {
          status = "failed";
          result = `فشل تحليل المهمة عبر Gemini: ${message.slice(0, 900)}`;
        }
      }

      const updatedAt = new Date().toISOString();
      await env.DB.prepare(
        "UPDATE tasks SET status = ?, result = ?, updated_at = ? WHERE id = ?"
      ).bind(status, result, updatedAt, id).run();

      return json({
        ok: status === "completed",
        task: { id, project: project || "default", goal, status, result, created_at: now, updated_at: updatedAt }
      }, 201);
    }

    if (path === "/api/tasks" && request.method === "GET") {
      const rawLimit = Number(url.searchParams.get("limit") || "30");
      const limit = Number.isFinite(rawLimit) ? Math.min(100, Math.max(1, Math.floor(rawLimit))) : 30;
      const result = await env.DB.prepare(
        "SELECT id, project, goal, status, result, created_at, updated_at FROM tasks ORDER BY created_at DESC LIMIT ?"
      ).bind(limit).all();
      return json({ ok: true, tasks: result.results ?? [] });
    }

    const taskId = taskIdFromPath(path);
    if (taskId && request.method === "GET") {
      const task = await env.DB.prepare(
        "SELECT id, project, goal, status, result, created_at, updated_at FROM tasks WHERE id = ?"
      ).bind(taskId).first();
      return task ? json({ ok: true, task }) : json({ error: "Task not found" }, 404);
    }

    if (taskId && request.method === "PATCH") {
      let body: { status?: unknown; result?: unknown };
      try { body = await request.json() as { status?: unknown; result?: unknown }; }
      catch { return json({ error: "Invalid JSON body" }, 400); }

      const allowed: TaskStatus[] = ["queued", "running", "waiting_input", "completed", "failed"];
      if (body.status !== undefined && (typeof body.status !== "string" || !allowed.includes(body.status as TaskStatus))) {
        return json({ error: "Invalid task status" }, 400);
      }
      if (body.result !== undefined && body.result !== null && typeof body.result !== "string") {
        return json({ error: "result must be a string or null" }, 400);
      }
      if (typeof body.result === "string" && body.result.length > 30000) {
        return json({ error: "result must be 30000 characters or fewer" }, 413);
      }

      const existing = await env.DB.prepare("SELECT id FROM tasks WHERE id = ?").bind(taskId).first();
      if (!existing) return json({ error: "Task not found" }, 404);
      const status = body.status as TaskStatus | undefined;
      const result = body.result as string | null | undefined;
      const now = new Date().toISOString();

      if (status !== undefined && result !== undefined) {
        await env.DB.prepare("UPDATE tasks SET status = ?, result = ?, updated_at = ? WHERE id = ?")
          .bind(status, result, now, taskId).run();
      } else if (status !== undefined) {
        await env.DB.prepare("UPDATE tasks SET status = ?, updated_at = ? WHERE id = ?")
          .bind(status, now, taskId).run();
      } else if (result !== undefined) {
        await env.DB.prepare("UPDATE tasks SET result = ?, updated_at = ? WHERE id = ?")
          .bind(result, now, taskId).run();
      } else {
        return json({ error: "Provide status and/or result" }, 400);
      }

      const task = await env.DB.prepare(
        "SELECT id, project, goal, status, result, created_at, updated_at FROM tasks WHERE id = ?"
      ).bind(taskId).first();
      return json({ ok: true, task });
    }

    return json({ error: "Not found" }, 404);
  }
};
